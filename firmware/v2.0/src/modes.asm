;; ----------------------------------------------------------------------------------------
;; The mode records: one 81-byte register record per mode. set_video_mode copies the
;; record for the mode number from the EPROM (by DMA) and writes it to the VGA chip.
;;
;; These lines are MODES.S from ss.source.082395.po, folder SECOND/MISC (docs/sources.md,
;; s06; firmware/original/MODES.S), changed only to this assembler's syntax: db 67h is
;; written .db 0x67, a comment starts with ;, and a label ends with :. The file's
;; segment and public lines are left out. Four records are not in MODES.S and are written
;; from the ROM in the same layout: vga_regs_FA, gs_regs_FA, gs_regs_FB, and gs_regs_FC,
;; whose MODES.S copy differs from ROM 1.4 in seven bytes (listed there).
;; Record layout: docs/reference/video-modes.md.
;; ----------------------------------------------------------------------------------------
